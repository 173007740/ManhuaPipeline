-- =============================================================
-- P2d 资产图册：锚点一律取台账规范名（禁止简称、禁止自造）
--
-- P3 / P4 那两条规则已经加过（Upgrade_P3分镜锚点规范名与台词.sql），
-- 但图册是分镜的上游：分镜抄的就是图册里的锚点写法。
-- 图册里写 @CHR-彦-正面，分镜照抄成 @CHR-彦-正面，于是
--「杨彦刚」这张 4View 母版图在资产绑定里一个都命中不了
--（匹配器反向兜底要求片段 ≥ 2 字，单字「彦」直接跳过），
-- 角色参考图槽全空，镜头被标 blocked_by_missing_asset。
-- 场景同理：图册里自造 @SCN-老屋院落 / @SCN-染坊作坊 / @SCN-外婆卧室，
-- 台账上根本没有，10 张场景母版图一张也进不了参考图槽。
--
-- 修法：把同一条「锚点规范」补进 P2d 的 OutputContract。改的是规则数据，
-- 下次跑即生效；已产出的图册不回改（产出保留原文是审计原则），重跑一次即可。
-- =============================================================

DECLARE @rule NVARCHAR(MAX) = N'

【锚点一律取台账规范名（禁止自造、禁止简称）】
@CHR- 用角色台账全名（@CHR-杨彦刚，不得简写成 @CHR-彦）；@SCN- 用场景台账名，只能是台账列出的那几个，禁止自造台账上没有的场景；@PRP- 用道具台账名；@AUD- 用声音台账名。
图册是分镜与提示词引用资产的唯一依据：这里写了简称或自造名，分镜照抄之后资产绑定落空，母版图进不了参考图槽，跨镜头外观就没人兜底了。
【图册每一项都要能对回台账条目】资产编号与名称照抄台账，不新增台账上没有的资产；视图后缀（正面 / 侧面 / 背面 / 飞行等）写在规范名之后。';

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + @rule,
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P2d'
  AND OutputContract NOT LIKE N'%锚点一律取台账规范名%';
