-- =============================================================
-- P3：镜长按内容选档，禁止全篇一刀切（可重复执行）
--
-- 现场：第 1 集 12 个单元，12 条镜头**全是 15s**——
-- 12 × 15 = 180 正好等于单集时长，是模型拿「180 ÷ 12」均分出来的，
-- 不是按内容定的。代价是：
--   1. 每条视频都用满 Seedance 2.0 的单段上限，越长越容易崩（形变/漂移/走样）
--   2. 12 条 × 15s 的生成成本与时间，远高于短镜头方案
--   3. 全篇长镜头没有一处短切，剪出来节奏发闷
-- 而且这个 15s 会被 KeyframePlanService 原样拼进 P4 的上下文，
-- 一路带到视频 API——P3 定死了，P4 就只能照抄。
--
-- 档位只有 5 / 11 / 15 三档（视频 API 支持的值，写别的会被
-- DirectorRuleValidator 判 SHOT_DURATION_ILLEGAL 硬拦），
-- 所以不是"想要多短就多短"，而是这三档里按内容挑。
-- =============================================================

DECLARE @p3 NVARCHAR(MAX) = N'

【镜长按内容选档，禁止一刀切】
镜长只能取 5 / 11 / 15 秒三档（视频 API 只支持这三档，写其他值会校验失败）。
按这一镜**实际要装多少内容**选档，不要按「单集时长 ÷ 单元数」均分——
均分出来的整齐数字说明你没在按内容思考：
  · 5 秒  ：空镜、过场、细节特写、反应镜头、一闪而过的动作。
            内容量撑不满 11 秒的，一律 5 秒，不许注水拉长。
  · 11 秒 ：有表演、有调度、有对话的一镜——最常用的档。
  · 15 秒 ：抒情长镜、大场面、复杂运镜（长横摇/长前推/升降）才用，
            一集里应当是个位数。
硬要求：一集之内必须至少用到两档，且 15 秒档不得超过镜头总数的三分之一。
禁止全篇同一档。';

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + @p3,
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P3'
  AND OutputContract NOT LIKE N'%镜长按内容选档%';

-- P4 也补一句：它拿到的上下文里明写着分镜时长，容易照抄。
-- 契约原本有「镜长由剧情倒推」，这里把「不许照抄分镜」说死。
DECLARE @p4 NVARCHAR(MAX) = N'

【镜长不许照抄分镜】
上下文里给出的分镜时长只是参考值，若它是整齐的均分数字（如全篇 15 秒），
说明分镜阶段没有按内容定档——此时你**必须按本段实际内容重新选档**（5 / 11 / 15），
不得照抄。单段越短越稳，能 5 秒说清的不要写 11 秒，能 11 秒说清的不要写 15 秒。';

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + @p4,
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P4'
  AND OutputContract NOT LIKE N'%镜长不许照抄分镜%';
