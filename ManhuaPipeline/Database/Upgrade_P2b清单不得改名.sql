/* P2b（资产清单定稿）：不得改名
   ------------------------------------------------------------------
   现象：道具「外婆旧木铁皮工具箱」出不来提示词，查下来是同一个箱子有三个名字：
         P2a 抽取入库   —— 外婆旧木铁皮工具箱   （资产表里的名字）
         P2b 定稿清单   —— 旧木铁皮工具箱（杨彦刚拖行）
         P2c3 出提示词  —— 外婆工具箱
         P2b 定稿时擅自把名字改短了，P2c 又照着自己那份写成第三个名字。
         入库是按名字把提示词回填到资产上的，三个名字互不包含，一条也写不进去 ——
         最新那次 P2c3 就报「1 条名字对不上台账，已跳过」，跳过的正是它。

   改法：契约里立规矩 —— 定稿清单不得改名，名称必须照抄 P2a 台账 / 资产表上的名字。
        要加括号说明（如「（杨彦刚拖行）」）就加在「备注 / 出图规格」那一列，不许加进名称。
        这一条跟 P2c 那条「名称必须照抄台账」是一套：改名字只会让后面每一站都对不上号，
        而改名本身带不来任何信息（备注列已经够写）。

   注：拼接用 CHAR(13)+CHAR(10) 而不是字面换行，这样这份脚本用 -i 直接跑也不会
       因为文件编码把 N'…' 里的换行读坏了。
   ------------------------------------------------------------------ */

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + CHAR(13)+CHAR(10)+N'【资产名称不得改名】清单里的「名称」一列必须照抄 P2a 台账 / 资产表上已有的名字：不得缩写、不得去掉或增加修饰词、不得在名称里加括号说明（「旧木铁皮工具箱（杨彦刚拖行）」这种——括号内容写进「备注 / 出图规格」列）。
原因：入库是按名字把后面每一站的产出回填到资产上的。这一步改一次名字，P2c 出提示词时就对不上资产、一条也写不进去（「外婆旧木铁皮工具箱」在 P2b 被写成「旧木铁皮工具箱」、P2c 又写成「外婆工具箱」，三个名字互不包含，结果这一条明明定的是要出图，却没有提示词、也没有图）。'
WHERE PackId = 1 AND StageKey = N'P2b'
  AND OutputContract NOT LIKE N'%资产名称不得改名%';

SELECT StageKey, Name, LEN(OutputContract) AS ContractLen
FROM DirectorSkillStages WHERE PackId = 1 AND StageKey = N'P2b';
