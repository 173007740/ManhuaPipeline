-- =============================================================
-- P3：每个单元必须拆成多条镜头（可重复执行）
--
-- 现场：第 1 集 12 个单元，跑出来 12 条镜头——一单元一镜。
-- 契约只管了镜长（5/11/15 选档），没规定一个单元该写几条镜头，
-- 模型就按最省事的写法来：整个单元压成一条长镜头。
-- 结果 3 分钟 12 镜，平均一镜十几秒，没有一处正反打、没有一处切特写。
--
-- 参考值：短剧正常节奏 3~5 秒/镜，180 秒该有 40 镜上下。
-- 但一次调用写不完 40 镜（12 镜就吃掉 1.1 万字符），
-- 所以先按「每单元 2~3 镜、全篇 24~36 镜」给，跑得过就跑，跑不动再分批。
-- =============================================================

DECLARE @rule NVARCHAR(MAX) = N'

【每个单元必须拆成多条镜头】
每个单元至少 2 条镜头；有对话、有调度、有情绪转折的单元拆 3 条。
**禁止一个单元只写一条镜头**——那等于把整个单元压成一个长镜头，
没有正反打、没有切特写、没有视点变化，剪出来是死的。
按这几种方式拆：
  · 按动作阶段拆：进入 → 动作 → 反应
  · 按视点拆：全景交代 → 近景表演 → 特写细节
  · 按对话拆：说话者 → 听者反应 → 回到说话者
全篇控制在 24~36 条镜头（12 个单元）。
篇幅紧张时的优先级：**先保证 12 个单元每个都有镜头**，再考虑加细——
宁可每单元都写满 2 条，也不要前面几个单元写得很细、后面单元空着。';

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + @rule,
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P3'
  AND OutputContract NOT LIKE N'%每个单元必须拆成多条镜头%';
