-- =============================================================
-- P3 / P4：视图后缀只能用资产板已有的视图（可重复执行）
--
-- 规范名那条规则补上之后，简称是自造的没了（@CHR-彦 → @CHR-杨彦刚），
-- 但模型转头开始造视图后缀：
--   @CHR-杨彦刚-城市态 / -小镇态（服装态）
--   @CHR-外婆-回忆动态态
--   @CHR-青鸟-衔瓦 / -衔花（动作态）
-- 资产板（P2c1）实际只有 4 View：正面 / 侧面 / 背面 / 面部特写，
-- 青鸟多一个飞行态。上面这些后缀没有对应资产图——
-- P4 照着它去取参考图，取不到，等于当年的 @CHR-彦 换个位置复发。
--
-- 规矩：服装态 / 动作态是这一镜的表演内容，写进 description，不进锚点。
-- =============================================================

DECLARE @rule NVARCHAR(MAX) = N'

【视图后缀只能用资产板已有的视图】
@CHR- 的视图后缀只许取：正面 / 侧面 / 背面 / 面部特写（@CHR-青鸟 另加 飞行态）。
服装态（城市态 / 小镇态 / 便服 / 正装 之类）与动作态（衔瓦 / 衔花 / 展翅 / 奔跑 之类）
**不是视图**，一律写进该镜的 description，禁止写进锚点。
理由：资产板上没有这些视图的图，锚点写了也取不到参考图，等于绑了一条空引用。';

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + @rule,
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey IN (N'P3', N'P4')
  AND OutputContract NOT LIKE N'%视图后缀只能用资产板已有的视图%';
