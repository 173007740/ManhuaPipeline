-- =============================================================
-- P3：把可拍范围写死（替换上次那条指向不存在的「分集细化」的规则）
--
-- 上次那条写的是「以【分集细化】给出的单元列表为准」——
-- 但本项目压根没有分集细化（P2b 是资产清单确认，产出里没有任何 1.1 这种单元号，
-- Episodes 表也只有第 1 集）。规则指向一个不存在的东西，等于没写：
-- 模型照着剧本里的 12 集梗概一路写到了 12.1。
--
-- 改成直接给边界：单元编号第一位是集号，只许写 1.x。
-- =============================================================

UPDATE DirectorSkillStages
SET OutputContract = REPLACE(
        OutputContract,
        N'以【分集细化】给出的单元列表为准，只写这些单元的分镜。',
        N'本项目当前可拍范围只有**第 1 集**：单元编号 1.1 ~ 1.12，共 12 个单元。**只许写这 12 个单元**。'
        + N'单元编号第一位是集号——2.1 / 3.1 / …… / 12.1 一律禁止出现，一个镜头都不许写。'
        + N'本次交付标准：12 个单元每个都写到（每单元 2~3 条镜头），不许只写开头几个单元就往下跳集。'),
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P3'
  AND OutputContract LIKE N'%以【分集细化】给出的单元列表为准%';
