-- 导演分镜（P3）：把「成片时长」定成硬约束。
--
-- 事故：第 2 集（projectId=58）分镜跑完 15 镜，合计 147 秒，而立项定的单集时长是 180 秒 ——
-- 少 33 秒（18%）。查下来是模型自己定了两档（过场 5 秒 / 长镜 11 秒）往下排，
-- 剧本里写明「静场约 8 秒」这类节奏标注也被压成 5 秒。
-- 成片时长是交付口径，差这么多等于没按立项做；而模型根本不知道这一集该多长 ——
-- 它的输入只有剧本和图册，单集时长在立项（Dramas.EpisodeDuration）上，从来没喂给过 P3。
--
-- 两条一起改，缺一不可：
--   1. 引擎注入（DirectorAgentService.DurationTargetSection）：P3 的输入末尾带上目标秒数与 ±5% 区间；
--   2. 产出契约（下面这段）：镜长怎么排、末尾必须写校验行。
--     只有注入没有契约，模型照样按自己那套档位排；只有契约没有注入，它不知道目标是多少。

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + CHAR(13)+CHAR(10)+CHAR(13)+CHAR(10)
  + N'【镜长与成片时长】镜长由剧情倒推，禁机械等分（同一集里不要只有两三种数值，那是没按内容排）。'
  + CHAR(13)+CHAR(10) + N'- 单个镜头 3~8 秒。需要更长的（长镜头、静场）以剧本标注为准，单镜最多不超过 12 秒；'
  + N'一个镜塞不下那么长的内容就拆成多镜，不要靠拉长单镜凑时长。'
  + CHAR(13)+CHAR(10) + N'- 剧本里写了具体秒数的节奏标注（例如「静场约 8 秒」「间隔约 6 秒」）照抄进对应镜的镜长，'
  + N'不得替换成自己那套档位——压掉了就不是剧本要的节奏。'
  + CHAR(13)+CHAR(10) + N'- 各镜镜长之和必须落在本集成片时长目标的 ±5% 之内（目标由引擎随输入注入）。'
  + N'排完自己加一遍：不够就补镜或把该长的镜排长，超了就压。差一截就交付等于没按立项做。'
  + N'引擎没给目标（立项没填单集时长）时按内容排，但末尾仍要写明实际合计。'
  + CHAR(13)+CHAR(10) + N'- 产出末尾必须单独写一行校验：「时长校验：共 N 镜 · 合计 X 秒 · 目标 Y 秒 · 偏差 Z 秒」。'
WHERE PackId = 1 AND StageKey = N'P3'
  AND OutputContract NOT LIKE N'%时长校验%';

SELECT StageKey, LEN(OutputContract) AS ContractLen FROM DirectorSkillStages WHERE PackId=1 AND StageKey=N'P3';
