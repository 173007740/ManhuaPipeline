/* 资产清单门禁自动放行
   ------------------------------------------------------------------
   现象：P2b 产出的是一张「请逐项回复 ✅/✏️/❌」的确认表；P2c1 拿到这张表，
        判定「清单未经用户确认 → 门禁未过」，于是输出一行 BLOCKED: ，
        整条流水线停在 P2c1，后面的出图提示词 / 分镜 / 终稿提示词全都没有。

   根因：两处配置自相矛盾。
        P2b 的 Gates（门禁）已经写了「本流水线已取消中途人工卡点」，
        但 P2b 的 OutputContract（产出契约）还写着「把 P2a 清单摆给用户逐项确认」。
        模型是照产出契约办事的，于是老老实实吐出一张待确认表；
        而 P2c1 的 Gates 又说「清单已在 P2b（人工卡点）经用户逐项确认」，
        可它的输入区里躺着的就是那张没人回复的表 —— 前后一对不上，就判门禁未过。

   改法：契约和门禁统一成一句话 —— 这条线上没有人在中途确认，
        清单出完即由系统放行，全部按 ✅ 保留。
        想改分级的人，事后照「## 本次假设」去改，或者重跑这一步。
   ------------------------------------------------------------------ */

-- 1. P2b：产出契约从「摆给用户逐项确认」改成「直接产出定稿清单」。
--    待确认表格是这次卡死的源头：模型一输出 ✅/✏️/❌，下游就认为事情还没定下来。
UPDATE DirectorSkillStages
SET OutputContract = N'产出定稿分级清单：逐项列出 CHR- / SCN- / PRP- / VFX- 编码、A（核心）/ B（常驻）/ C（一次性）分级、是否出图、出图规格（4 View 资产板 / 单张外观设定 / 不出图）。

本流水线没有中途人工卡点：清单在本阶段定稿后即由系统放行进入 P2c 三个批次，不存在「摆给用户逐项回复」这一环。
分级拿不准的项，按行业惯例取最合理的值直接定稿，不要留成待确认项，不要在表格里放 ✅ / ✏️ / ❌ 这类待回复符号。
替用户做出的判断（升级、降级、删除了哪一项，以及理由）在末尾用「## 本次假设」列出，不超过 5 条，让他事后一眼看得到、也改得动。'
WHERE StageKey = N'P2b';

-- 2. P2c 三个批次：门禁里「已在 P2b 经用户逐项确认」这句已经不成立（那一环取消了），
--    换成「上游清单即定稿清单，系统已放行」。用 REPLACE 只换这一句，
--    后面「本阶段负责第 N 批…」的批次说明原样保留。
UPDATE DirectorSkillStages
SET Gates = REPLACE(Gates,
    N'资产清单已在 P2b（人工卡点）经用户逐项确认后才流到本阶段，此举即视为已下达出图口令。',
    N'上游 P2b 产出的分级清单即为定稿清单，系统已自动放行、全部按 ✅ 保留，此举即视为已下达出图口令。')
WHERE StageKey = N'P2c1';

UPDATE DirectorSkillStages
SET Gates = REPLACE(Gates,
    N'资产清单已在 P2b（人工卡点）经用户逐项确认，此举即视为已下达出图口令。',
    N'上游 P2b 产出的分级清单即为定稿清单，系统已自动放行、全部按 ✅ 保留，此举即视为已下达出图口令。')
WHERE StageKey IN (N'P2c2', N'P2c3');

-- 3. 三个批次的拒绝理由清单里补一条：不许再拿「没收到逐项回复」当拒绝的由头。
--    这是这次实际触发的那一条，不写死就还会再犯。
UPDATE DirectorSkillStages
SET Gates = REPLACE(Gates,
    N'不得以「未收到明确出图口令」',
    N'不得以「未收到明确出图口令」「清单未经用户逐项回复」')
WHERE StageKey IN (N'P2c1', N'P2c2', N'P2c3')
  AND Gates LIKE N'%未收到明确出图口令%'
  AND Gates NOT LIKE N'%清单未经用户逐项回复%';
