-- =============================================================
-- P3：只写有剧本/单元的集，禁止照全剧梗概扩写后续集（可重复执行）
--
-- 现场：项目 57 的 P1 是「全剧 12 集梗概」，每集一句话
--   （"第1集陌生人 → 第6集共染 → 第9集照片揭示渊源 → 第12集分一碗面"），
-- 真正有内容的只有第 1 集。P3 却照着梗概一路写到了 10.1，
-- 43 帧全是拿一句话自行扩写的——没单元、没台词、没剧本支撑，
-- 分镜页看着一应俱全，实际全是编的。
--
-- 规矩：以【分集细化】给出的单元列表为准。上下文里没有单元内容的集，
-- 一个镜头都不许写。
-- =============================================================

DECLARE @rule NVARCHAR(MAX) = N'

【只写有剧本的集】
以【分集细化】给出的单元列表为准，只写这些单元的分镜。
全剧梗概（"第N集……"一句话）**不是剧本**：梗概里提到的后续集没有单元划分、
没有台词、没有动作内容，禁止照着它自行扩写那些集的分镜。
本次要写哪些单元，以上下文里实际给出的单元列表为界；列表到哪，分镜就写到哪，
不要自行往下续集数。';

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + @rule,
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P3'
  AND OutputContract NOT LIKE N'%只写有剧本的集%';
