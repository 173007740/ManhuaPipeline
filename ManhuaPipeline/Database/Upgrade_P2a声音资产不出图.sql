-- =============================================================
-- P2a：AUD- 声音资产不产出图像（真跑之后发现的，可重复执行）
--
-- 第一次真跑 P2a，模型把 38 个实体的「资产图需求」列一律写成「必须出图：……」，
-- 连 AUD-BGM-合流高燃、AUD-静场留白 这类纯声音项也写出图 —— 典型的表格套模板。
-- 根因是 P2a 的产出契约只讲了 CHR/SCN/PRP/VFX 的出图规则，没说清 AUD- 该产出什么。
--
-- 修法：在 OutputContract 补一条，明确 AUD- 的资产需求列写「音色/SFX/BGM 规格与时长」，
-- 禁止写出图。改的是规则数据，下次跑即生效。
--
-- 本次已产生的清单不回改：产出保留 LLM 原文是审计原则，改了就说不清当初跑出了什么。
-- =============================================================

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + N'

【资产需求列的分类写法（避免套模板）】
CHR- 写 4 View 资产板 / SCN- 写场景母版+拼接图+站位版 / PRP- 写道具资产图 / VFX- 写特效资产图。
AUD- 是声音资产，不产出任何图像，其资产需求列必须写「音色/SFX/BGM 规格与时长」，禁止出现"出图"字样。
不需要资产化的实体（如 C 级群像、一次性投影）明确写"不出图"并给出降级理由。',
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P2a'
  AND OutputContract NOT LIKE N'%资产需求列的分类写法%';
