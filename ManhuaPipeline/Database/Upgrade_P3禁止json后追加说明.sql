-- =============================================================
-- P3：json 块必须完整闭合，禁止在其后追加任何说明（可重复执行）
--
-- 事故：step 75 产出 15121 字符，json 块里最后一个对象缺了「}」、
-- 数组缺了「]」就 ``` 收尾，后面还跟了一大段创作说明
-- （"1. 无逐场剧本与台词文本… 2. 城市态→小镇态转换点… 3. 青鸟登场限定…"）。
-- JSON 语法不完整 → 解析器提不出来 → 兜底找镜号表格也没有
-- → ImportedCount = 0，整批白跑，库里还是上一版（表现为"改了规则但产出没变"）。
--
-- 根子：输出额度就那么多，说明文字挤掉的是 json 收尾的那几个字符。
-- 规矩：先保证 json 完整闭合，其余一律不许写。
-- =============================================================

DECLARE @rule NVARCHAR(MAX) = N'

【输出只许一个 json 块，且必须完整闭合】
1. 全文只输出一个 ```json 代码块，块内是一个完整的数组：以 [ 开始、以 ] 结束，
   每一个 { 都有配对的 }。**收尾前自己数一遍括号**——
   上次就是因为最后一个对象缺了 } 和 ]，整批解析失败、入库 0 条、白跑一次。
2. json 块之后**禁止追加任何内容**：不要写说明、注释、创作手记、自检清单、
   "补充说明""备注"之类。这些文字会挤占输出额度，把 json 的尾巴挤没了。
3. 篇幅不够时的正确做法：压缩每条镜头的 description 字数（控制在 40 字内）、
   或减少每个单元的镜头数，**但必须保证 json 完整闭合**。
   宁可只写 12 个单元各 2 条、json 完整，也不要写 28 条却收不了尾。';

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + @rule,
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P3'
  AND OutputContract NOT LIKE N'%输出只许一个 json 块%';
