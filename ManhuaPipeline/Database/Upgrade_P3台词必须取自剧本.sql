-- =============================================================
-- P3：台词必须逐字取自剧本，禁止自造（可重复执行）
--
-- 现场：剧本（P1）第 1 集是刻意设计的静默戏——
--   台词语速自检卡写着「（无台词。只有风声、远处蝉鸣、瓦片弹跳的"叮"。）」
--   「@杨彦刚（张嘴想说什么，没出声。）」
-- 26 条镜头里 25 条 dialogue 是「无」，忠实于剧本，这没问题。
--
-- 问题在唯一那条：剧本里真正的台词是「……明天再说。」，分镜没用它，
-- 反而自己造了一句 OS 旁白：
--   @AUD-杨彦刚-OS：「三十七楼，做了五年广告，最后连一张辞职信都没人看。」
-- 而且 @AUD- 这个前缀根本不在四类台账里（CHR / SCN / PRP / VFX），
-- 没有对应的资产卡，绑不上。
--
-- 规矩：分镜不写台词，只搬运台词。
-- =============================================================

DECLARE @rule NVARCHAR(MAX) = N'

【台词必须逐字取自剧本，禁止自造】
dialogue 字段只做一件事：把剧本里已有的台词原样搬过来，一个字都不许改、不许加、不许缩写。
  · 剧本这一处写了台词 → 照抄原文（含省略号、标点）。
  · 剧本这一处标注「无台词 / 没说话 / 没出声 / 只有环境音」→ dialogue 写「无」，
    不要替人物补台词，也不要写旁白、OS、内心独白。
  · 剧本里没有的台词，一个字都不许出现。
禁止自造锚点前缀：@CHR- / @SCN- / @PRP- / @VFX- 之外不许发明新的（如 @AUD-）。
旁白/音效若剧本有要求，写进镜头描述或时间轴里用普通文字描述，不要做成锚点。';

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + @rule,
    UpdatedAt = SYSDATETIME()
WHERE PackId = 1 AND StageKey = N'P3'
  AND OutputContract NOT LIKE N'%台词必须逐字取自剧本%';
