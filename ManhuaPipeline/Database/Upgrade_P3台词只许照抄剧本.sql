/* P3 分镜：台词必须逐句取自剧本，禁止自创。
   背景：这一站以前只拿得到资产图册（剧本只在 P2a 那一站出现过一次，没往下传），
   模型手里没有台词，于是 Dialogue 全写「无」，
   唯一那句 OS「三十七楼，做了五年广告…」是它自己编的——剧本里查无此句。
   引擎侧已补上剧本注入（ExtraSourcesOf P3 -> P1），这里把规矩写死。 */

UPDATE DirectorSkillStages
SET OutputContract = OutputContract + N'

【台词只许照抄剧本，禁止自创】
每镜【台词】段逐句取自上游 P1 剧本（含剧本末尾的「台词语速自检卡」），原文照抄、一字不改，
说话人用台账规范名（格式如 @AUD-杨彦刚-OS）。
剧本这一镜没有台词的，写「无」——默片镜头是常态，禁止为了填满而自己写台词。
剧本末尾若有台词语速自检卡，那几句必须逐句落进对应镜，一句都不许漏。
分镜是剧本的镜头化转写，不是二次创作：写了剧本里没有的台词，后面的提示词和配音会一起跑偏。
【单元划分以剧本为准】单元从剧本的场号 / 段落切出来，禁止自行发明单元号。'
WHERE PackId = 1
  AND StageKey = N'P3'
  AND OutputContract NOT LIKE N'%台词只许照抄剧本%';

SELECT @@ROWCOUNT AS Affected;
