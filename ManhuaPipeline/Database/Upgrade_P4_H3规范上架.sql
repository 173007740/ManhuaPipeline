- 能量波动/震荡 → 可见空气波纹荡开、涟漪状折射扭曲
- 强大气场/威压/压迫感 → 尘环沿地面向外推进、碎石弹起、衣袍发丝被持续吹起
- 力量汇聚/蓄力 → 光尘向一点螺旋汇聚、周围空气扭曲
- 能量爆发/炸裂 → 环形冲击波荡开 + 碎屑飞散 + 地面掀起尘环
- 氛围感/高级感/质感 → 落为具体的光、材质与运动

每个特效或氛围描写至少给出「形态 + 运动 + 环境反馈」三项。
本表不豁免特效非实体铁律：去水只要求写具体形态，绝不意味着特效可以具象为人物或占据主体构图位。
