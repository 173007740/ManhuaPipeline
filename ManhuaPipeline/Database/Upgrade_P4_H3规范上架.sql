形态（丝/雾/环/浪/弧光/光带/粒子/纹路）、边界（清晰轮廓还是渐隐消散）、
运动（喷射/环绕/炸开/汇聚/流淌的方向与速度）、材质（半透明/流动/带碎屑/带电弧/金属反光）。

